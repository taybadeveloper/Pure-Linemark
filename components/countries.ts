export interface Country {
  code: string;
  name: string;
  dial: string;
  example: string;
  digits: number;
  format: number[];
}

/** Insert spaces between digit groups, e.g. [4,7] + "03001234567" -> "0300 1234567" */
export function formatPhone(digits: string, groups: number[]): string {
  let out = "";
  let index = 0;
  for (const group of groups) {
    if (index >= digits.length) break;
    if (out) out += " ";
    out += digits.slice(index, index + group);
    index += group;
  }
  return out;
}

/** Default digit grouping for a given national number length */
function formatFor(digits: number): number[] {
  if (digits === 11) return [4, 3, 4];
  if (digits === 10) return [3, 3, 4];
  if (digits === 9) return [3, 3, 3];
  if (digits === 8) return [4, 4];
  if (digits === 7) return [3, 4];
  if (digits === 6) return [3, 3];
  return [3, 3, 4];
}

